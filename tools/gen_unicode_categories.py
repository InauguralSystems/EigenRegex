#!/usr/bin/env python3
"""Generate EigenRegex Unicode tables exclusively from pinned UCD 15.0 files."""
import hashlib,json,urllib.request
from pathlib import Path
CATEGORIES=("L","Lu","Ll","Lt","Lm","Lo","N","Nd","Nl","No",
 "M","Mn","Mc","Me","C","Cc","Cf","Cs","Co",
 "Z","Zs","Zl","Zp","P","Pc","Pd","Ps","Pe","Pi","Pf","Po",
 "S","Sm","Sc","Sk","So")
ROOT=Path(__file__).resolve().parents[1]; UCD=ROOT/'.cache'/'ucd'/'15.0.0'; VERSION='15.0.0'
URLS={n:f"https://www.unicode.org/Public/15.0.0/ucd/{n}" for n in ('UnicodeData.txt','CaseFolding.txt')}
SHA256={'UnicodeData.txt':'806e9aed65037197f1ec85e12be6e8cd870fc5608b4de0fffd990f689f376a73','CaseFolding.txt':'cdd49e55eae3bbf1f0a3f6580c974a0263cb86a6a08daa10fbf705b4808a56f7'}
START,END='# BEGIN GENERATED UNICODE CATEGORIES','# END GENERATED UNICODE CATEGORIES'
def pinned(n):
 p=UCD/n
 if not p.is_file():
  UCD.mkdir(parents=True,exist_ok=True); print(f'download {URLS[n]} -> {p}')
  try: urllib.request.urlretrieve(URLS[n],p)
  except Exception as e: raise SystemExit(f'missing download for {n}: {e}')
 got=hashlib.sha256(p.read_bytes()).hexdigest()
 if got!=SHA256[n]: raise SystemExit(f'sha256 mismatch for {p}: expected {SHA256[n]}, got {got}')
 print(f'verified {n} sha256={got}')
 return p
def categories(p):
 out={}; pending=None
 for line in p.read_text().splitlines():
  f=line.split(';'); cp,name,cat=int(f[0],16),f[1],f[2]
  if name.endswith(', First>'): pending=(cp,cat); continue
  is_last=name.endswith(', Last>') and pending
  lo=pending[0] if is_last else cp
  out.setdefault(cat,[]).append((lo,cp))
  if is_last: pending=None
 return out
def folds(p):
 parent={}
 def find(x):
  parent.setdefault(x,x)
  while parent[x]!=x: parent[x]=parent[parent[x]]; x=parent[x]
  return x
 def union(a,b):
  a,b=find(a),find(b)
  if a!=b: parent[b]=a
 for raw in p.read_text().splitlines():
  line=raw.split('#',1)[0].strip()
  if not line: continue
  a,status,b,*_=[x.strip() for x in line.split(';')]
  if status in ('C','S'): union(int(a,16),int(b,16))
 groups={}
 for cp in parent: groups.setdefault(find(cp),[]).append(cp)
 return {cp:sorted(v) for v in groups.values() if len(v)>1 for cp in v}
def coalesce(points):
 out=[]
 for cp in sorted(set(points)):
  if out and cp==out[-1][1]+1: out[-1][1]=cp
  else: out.append([cp,cp])
 return out
def chunks(m,n=900):
 x=list(m.items()); return [dict(x[i:i+n]) for i in range(0,len(x),n)]
def main():
 cats,fold=categories(pinned('UnicodeData.txt')),folds(pinned('CaseFolding.txt')); table={}
 for wanted in CATEGORIES:
  raw=sorted(r for cat,v in cats.items() if cat==wanted or (len(wanted)==1 and cat.startswith(wanted)) for r in v)
  rs=coalesce(cp for lo,hi in raw for cp in range(lo,hi+1))
  table[wanted]=rs
 meta=f'''{START}\n# Generated by tools/gen_unicode_categories.py from Unicode {VERSION}.\n# UnicodeData.txt: {URLS['UnicodeData.txt']} sha256={SHA256['UnicodeData.txt']}\n# CaseFolding.txt: {URLS['CaseFolding.txt']} sha256={SHA256['CaseFolding.txt']}\n_unicode_data_version is "{VERSION}"\n_unicode_property_ranges is null\n{END}'''
 path=ROOT/'regex.eigs'; text=path.read_text(); text=text[:text.index(START)]+meta+text[text.index(END)+len(END):]
 path.write_text(text)
 header=f'''# Generated by tools/gen_unicode_categories.py from Unicode {VERSION}.\n# UnicodeData.txt: {URLS['UnicodeData.txt']} sha256={SHA256['UnicodeData.txt']}\n# CaseFolding.txt: {URLS['CaseFolding.txt']} sha256={SHA256['CaseFolding.txt']}\n'''
 (ROOT/'unicode_categories.eigs').write_text(header+'define _generated_unicode_property_ranges(_) as:\n    return '+json.dumps(table,separators=(',',':'))+'\n')
 (ROOT/'unicode_casefold.eigs').write_text(header+'# Single representation; runtime derives byte and canonical tables on first (?i).\ndefine _generated_case_scalar_tables(_) as:\n    return '+json.dumps(chunks({str(cp):v for cp,v in fold.items()}),separators=(',',':'))+'\n')
 print(f'generated Unicode assets ({len(fold)} folded scalars)')
if __name__=='__main__': main()
