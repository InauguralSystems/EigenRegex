#!/usr/bin/env python3
"""Generate the Unicode-property AST table embedded in regex.eigs."""
import json
import unicodedata
from pathlib import Path

CATEGORIES = ("L", "Lu", "Ll", "Lt", "Lm", "Lo", "N", "Nd", "Nl", "No", "P", "S", "Z")
ROOT = Path(__file__).resolve().parents[1]
START = "# BEGIN GENERATED UNICODE CATEGORIES"
END = "# END GENERATED UNICODE CATEGORIES"


def ranges_for(category):
    wanted = lambda cp: (unicodedata.category(chr(cp)).startswith(category)
                         if len(category) == 1 else unicodedata.category(chr(cp)) == category)
    out, start = [], None
    for cp in range(0x110000):
        yes = not (0xD800 <= cp <= 0xDFFF) and wanted(cp)
        if yes and start is None:
            start = cp
        if start is not None and (not yes or cp == 0x10FFFF):
            out.append((start, cp if yes else cp - 1)); start = None
    return out


def boxes(lo, hi):
    """Cover a same-width UTF-8 interval with byte-range Cartesian boxes."""
    a, b = list(chr(lo).encode()), list(chr(hi).encode())
    assert len(a) == len(b)
    def cover(x, y, pos):
        if pos == len(x): return [[]]
        if x[pos] == y[pos]:
            return [[(x[pos], x[pos]), *tail] for tail in cover(x, y, pos + 1)]
        result = []
        xmax = x[:]; xmax[pos + 1:] = [191] * (len(x) - pos - 1)
        result += cover(x, xmax, pos)
        if x[pos] + 1 <= y[pos] - 1:
            result.append([(x[pos] + 1, y[pos] - 1), *([(128, 191)] * (len(x) - pos - 1))])
        ymin = y[:]; ymin[pos + 1:] = [128] * (len(y) - pos - 1)
        result += cover(ymin, y, pos)
        return result
    return cover(a, b, 0)


def utf8_boxes(ranges):
    result = []
    for lo, hi in ranges:
        for floor, ceiling in ((0,0x7f),(0x80,0x7ff),(0x800,0xffff),(0x10000,0x10ffff)):
            a, b = max(lo, floor), min(hi, ceiling)
            if a <= b: result.extend(boxes(a, b))
    return result


def ast(rs):
    branches = []
    for box in utf8_boxes(rs):
        nodes = [["class", 0, [[lo, hi]]] for lo, hi in box]
        branches.append(nodes[0] if len(nodes) == 1 else ["concat", nodes])
    
    while len(branches) > 200:
        branches = [["alt", branches[i:i+200]] for i in range(0, len(branches), 200)]
    return branches[0] if len(branches) == 1 else ["alt", branches]


def complement(rs):
    out, at = [], 0
    for lo, hi in rs:
        if at < lo: out.append((at, lo - 1))
        at = hi + 1
    if at <= 0x10ffff: out.append((at, 0x10ffff))
    clean = []
    for a, b in out:
        if a <= 0xd7ff: clean.append((a, min(b, 0xd7ff)))
        if b >= 0xe000: clean.append((max(a, 0xe000), b))
    return clean


def main():
    table = {}
    for cat in CATEGORIES:
        rs = ranges_for(cat)
        table[cat] = ast(rs)
        table["!" + cat] = ast(complement(rs))
    payload = (f"{START}\n# Generated by tools/gen_unicode_categories.py; Unicode {unicodedata.unidata_version}.\n"
               f"_unicode_data_version is {json.dumps(unicodedata.unidata_version)}\n"
               f"_unicode_property_asts is {json.dumps(table,separators=(',',':'))}\n{END}")
    path = ROOT / "regex.eigs"
    text = path.read_text()
    if START in text:
        text = text[:text.index(START)] + payload + text[text.index(END)+len(END):]
    else:
        text = text.replace("_rx_error is \"\"", payload + "\n\n_rx_error is \"\"", 1)
    path.write_text(text)

if __name__ == "__main__": main()
