#!/usr/bin/env python3
"""Generate compact Unicode-property code-point ranges for regex.eigs."""
import json
import unicodedata
from pathlib import Path

CATEGORIES = ("L", "Lu", "Ll", "Lt", "Lm", "Lo", "N", "Nd", "Nl", "No", "P", "S", "Z")
ROOT = Path(__file__).resolve().parents[1]
START = "# BEGIN GENERATED UNICODE CATEGORIES"
END = "# END GENERATED UNICODE CATEGORIES"


def ranges_for(category):
    wanted = lambda cp: (unicodedata.category(chr(cp)).startswith(category)
                         if len(category) == 1 else unicodedata.category(chr(cp)) == category)
    out, start = [], None
    for cp in range(0x110000):
        yes = not (0xD800 <= cp <= 0xDFFF) and wanted(cp)
        if yes and start is None:
            start = cp
        if start is not None and (not yes or cp == 0x10FFFF):
            out.append((start, cp if yes else cp - 1)); start = None
    return out


def simple_fold_classes():
    """Return full transitive classes of one-scalar Unicode case mappings.

    Connecting lower/upper/title/casefold mappings and taking connected
    components is important: pairwise tables miss third members such as the
    Kelvin sign, long s, final sigma, and micro sign.
    """
    parent = list(range(0x110000))
    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]; x = parent[x]
        return x
    def union(a, b):
        a, b = find(a), find(b)
        if a != b: parent[b] = a
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF: continue
        c = chr(cp)
        for mapped in (c.lower(), c.upper(), c.title(), c.casefold()):
            if len(mapped) == 1: union(cp, ord(mapped))
    classes = {}
    for cp in range(0x110000):
        if not 0xD800 <= cp <= 0xDFFF:
            classes.setdefault(find(cp), []).append(cp)
    return {cp: members for members in classes.values() if len(members) > 1 for cp in members}


def coalesce(points):
    out = []
    for cp in sorted(points):
        if out and cp == out[-1][1] + 1: out[-1][1] = cp
        else: out.append([cp, cp])
    return out


def utf8(cp):
    return list(chr(cp).encode("utf-8"))


def main():
    table = {cat: ranges_for(cat) for cat in CATEGORIES}
    folds = simple_fold_classes()
    for cat in CATEGORIES:
        members = {cp for lo, hi in table[cat] for cp in range(lo, hi + 1)}
        table["i:" + cat] = coalesce({variant for cp in members for variant in folds.get(cp, [cp])})
    payload = (f"{START}\n# Generated by tools/gen_unicode_categories.py; Unicode {unicodedata.unidata_version}.\n"
               f"_unicode_data_version is {json.dumps(unicodedata.unidata_version)}\n"
               "_unicode_property_ranges is null\n"
               f"{END}")
    path = ROOT / "regex.eigs"
    text = path.read_text()
    if START in text:
        text = text[:text.index(START)] + payload + text[text.index(END)+len(END):]
    else:
        text = text.replace("_rx_error is \"\"", payload + "\n\n_rx_error is \"\"", 1)
    # Keep literal matching's generated lookup in sync with the same complete
    # closure used for properties.  Split dictionaries keep EigenScript
    # literals below the compiler's per-expression size limit.
    variants = {str(cp): [utf8(v) for v in members] for cp, members in folds.items()}
    canonical = {str(cp): min(members) for cp, members in folds.items()}
    def chunks(mapping, size=900):
        items = list(mapping.items())
        return [dict(items[i:i + size]) for i in range(0, len(items), size)]
    lines = text.splitlines()
    for i, line in enumerate(lines):
        if line.startswith("_case_folds is "):
            lines[i] = "_case_folds is " + json.dumps(chunks(canonical), separators=(",", ":"))
        if line.startswith("_case_byte_tables is "):
            lines[i] = "_case_byte_tables is " + json.dumps(chunks(variants), separators=(",", ":"))
    path.write_text("\n".join(lines) + "\n")
    data = (f"# Generated by tools/gen_unicode_categories.py; Unicode {unicodedata.unidata_version}.\n"
            "define _generated_unicode_property_ranges(_) as:\n"
            f"    return {json.dumps(table,separators=(',',':'))}\n")
    (ROOT / "unicode_categories.eigs").write_text(data)

if __name__ == "__main__": main()
